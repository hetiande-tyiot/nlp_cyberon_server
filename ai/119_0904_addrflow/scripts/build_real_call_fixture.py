cases = []
for filename, (note, utterances) in EXPECTED.items():
    path = os.path.join(LOG_DIR, filename)
    if not os.path.exists(path):
        print(f"  跳過（找不到）：{filename}")
        continue
    data = json.load(open(path, encoding="utf-8"))
    spoken = {
        t["text"] for t in (data.get("transcript") or [])
        if t.get("role") == "caller"
    }
    rows = []
    for text, want_d, want_r, want_n in utterances:
        if text not in spoken:
            print(f"  ⚠ 原話已不在該通 transcript 中：{text[:24]}…")
        parts = extract_street_address_components(text)
        rows.append({
            "text": text,
            "expect_district": want_d,
            "expect_road": want_r,
            "expect_number": want_n,
            "observed": {
                "district": parts.get("address_district"),
                "road": parts.get("address_road"),
                "number": parts.get("address_number"),
                "rebuilt": build_street_address(
                    parts.get("address_district"),
                    parts.get("address_road"),
                    parts.get("address_number"),
                    existing=text,
                ),
            },
        })
    cases.append({
        "id": filename.replace(".json", ""),
        "note": note,
        "orig_case_address": data.get("address"),
        "orig_location_type": data.get("location_type"),
        "utterances": rows,
    })
    print(f"  ✓ {filename}")

