def match_rescue_subcategory(
    text: str,
) -> Tuple[Optional[str], Optional[float], Optional[str]]:
    """
    以高貼合關鍵詞直判救護子類別。

    Returns
    -------
    (sub_category, confidence, matched_keyword)
        未命中時三者皆為 None。
    """
    s = (text or "").strip()
    if not s:
        return None, None, None

    # 去空白後再比對，降低 STT 斷詞影響（「燒 炭」）
    compact = "".join(s.split())

    for sub_cat, keywords in RESCUE_SUBCATEGORY_KEYWORDS:
        for kw in keywords:
            if not kw:
                continue
            if kw in s or kw in compact:
                return sub_cat, KEYWORD_MATCH_CONF, kw
    return None, None, None
