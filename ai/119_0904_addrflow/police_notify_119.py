def lookup_need_police(
    main_category: Optional[str],
    sub_category: Optional[str],
) -> Optional[bool]:
    """
    查「此案類是否須通知110」。

    回 True／False 表示本表有結論；回 None 表示本表不收這個案類
    （分類器標籤對不上規則案類，或主類別不在救護／火警／緊急救援），
    呼叫方應維持 `NeedPolice` 既有值、不要改寫。
    """
    if not main_category or not sub_category:
        return None
    return NEED_POLICE_BY_CATEGORY.get((main_category, sub_category))


def is_mandatory_notify(
    main_category: Optional[str],
    sub_category: Optional[str],
) -> bool:
    """此案類是否為 SOP 明訂必須通知110（True 才算；None 與 False 都回 False）。"""
    return lookup_need_police(main_category, sub_category) is True


