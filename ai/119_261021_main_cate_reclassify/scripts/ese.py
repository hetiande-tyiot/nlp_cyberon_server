# --- 2. 台語混淆權重 ---
SIMILARITY_WEIGHTS = {
    ("k", "h"): 0.5,
    ("h", "k"): 0.5,
    ("k", "s"): 0.5,
    ("s", "k"): 0.5,
    ("p", "t"): 0.3,
    ("t", "p"): 0.3,
    ("p", "k"): 0.3,
    ("k", "p"): 0.3,
    ("a", "ia"): 0.4,
    ("ia", "a"): 0.4,
    ("a", "ah"): 0.4,
    ("ah", "a"): 0.4,
}


def char_to_tl(char: str) -> str:
    """單個漢字轉台語羅馬拼音；若無對映則返回空字串。"""
    return TAIWANESE_MAP.get(char, "")


def chinese_to_tl(text: str) -> str:
    """把一整段中文轉成台語羅馬拼音序列，用 '-' 連接。"""
    syllables = []
    for c in text:
        tl = char_to_tl(c)
        if tl:
            syllables.append(tl)
    return "-".join(syllables)


# --- 3. 加權編輯距離 ---
def weighted_edit_distance(s1: str, s2: str) -> float:
    m, n = len(s1), len(s2)
    dp = [[0] * (n + 1) for _ in range(m + 1)]

    for i in range(m + 1):
        dp[i][0] = i
    for j in range(n + 1):
        dp[0][j] = j

    for i in range(1, m + 1):
        for j in range(1, n + 1):
            if s1[i - 1] == s2[j - 1]:
                cost = 0
            else:
                cost = SIMILARITY_WEIGHTS.get((s1[i - 1], s2[j - 1]), 1.0)

            dp[i][j] = min(
                dp[i - 1][j] + 1,  # 刪除
                dp[i][j - 1] + 1,  # 插入
                dp[i - 1][j - 1] + cost,  # 替換
            )

    return dp[m][n]


# --- 4. 相似度評分 ---
def similarity_score(s1: str, s2: str) -> float:
    """根據加權編輯距離計算相似度（0~1）。"""
    if not s1 and not s2:
        return 1.0
    if not s1 or not s2:
        return 0.0

    d = weighted_edit_distance(s1, s2)
    max_len = max(len(s1), len(s2))
    return 1 - d / max_len
